"""AZ master skeleton: SK_AZ_Master = exact copy of the MetaHuman body skeleton + our extra leaf bones.

Why: /Game/MetaHumans/Common/** and the hero body are regenerated by MetaHuman assembly (and not in git), so the
master lives in our folder. The hero keeps metahuman_base_skel and plays master animations through
CompatibleSkeletons (metahuman_fixup.py). Bones of the MetaHuman part are never renamed, moved or re-oriented.

Run in the editor (Python):   MODE = "duplicate" | "finish" | "verify";  exec(open(r"C:/UnrealEngine/Games/AZ/Tools/az_master_skeleton.py").read())
Between "duplicate" and "finish" the mesh copy is moved onto SK_AZ_Master in C++ (USkeletalMesh::SetSkeleton is not
reachable from Python).
MODE "add_bones" on the MASTER mesh: the master skeleton is referenced by that one mesh only, so UE's commit rebuilds the
skeleton FROM the mesh - its ref pose becomes the hero's proportions and its per-bone translation retargeting modes get
scrambled. Afterwards, in C++ (no Python API): copy metahuman_base_skel's raw ref pose (FReferenceSkeletonModifier) and
its GetBoneTranslationRetargetingMode per bone onto SK_AZ_Master, save, then MODE "verify" and MODE "compat_test"
(retarget=False AND retarget=True must both PASS). On the hero body (skeleton shared by many assets) UE merges instead,
nothing to fix there.
Report: Saved/az_master_report.txt
"""
